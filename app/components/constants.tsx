export const cleanPhone = (raw: string): string =>
	raw.replace(/[\s\-\(\)]/g, "");

export const buildUri = (
	platform: "whatsapp" | "viber",
	phone: string,
	message: string,
): string => {
	const encoded = encodeURIComponent(message);
	switch (platform) {
		case "whatsapp":
			return `https://wa.me/${phone}?text=${encoded}`;
		case "viber":
			return `viber://chat?number=%2B${phone.replace(/^\+/, "")}`;
	}
};

